#!/usr/bin/env python3
"""Goal_Planner.xlsx — a LIVE formula workbook generated from the same model
as the page.

    node build/export_model.mjs samples/sample_plan.json > model.json
    python3 build/build_xlsx.py model.json samples/Goal_Planner_sample.xlsx

Rule 1: generated, never hand-maintained. Rule 2: parity-gated
(tests/parity_xlsx.py recalculates it with LibreOffice and compares
Year_by_year with the JS engine, ₹1 per cell).

How the engine becomes formulas (no macros, no iterative calculation,
Excel-2007-era functions only):

* Engine_Growth   one row per year, one column per holding per field:
                  mid-year growth, step-ups, lock-ins, year-end tax, cost basis.
* Engine_Withdraw one row per (year, goal slot). Goals are drawn in the
                  engine's order (essential first, then by start year). For each
                  slot: what is available, the tax a FULL draw of every band
                  would cost (sequential exemption, in withdraw order), which
                  band the need ends in, then the final split and its tax.
* Engine_GrossUp  the one step that is not closed form: inside the band where
                  the need ends, the equal-rupee level λ that nets exactly the
                  need. net(λ) is piecewise linear, so a safeguarded Newton step
                  on the exact slope lands on it in a few iterations; K fixed
                  iteration blocks, no circular references.

Required-corpus curve and solver cards need a search per value and have no
honest formula form: they go on Analysis, as values, with a banner.
"""
import json
import sys
from datetime import date

from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter as L
from openpyxl.workbook.defined_name import DefinedName
from openpyxl.worksheet.datavalidation import DataValidation

MAXY = 60          # year rows available (a plan longer than this is flagged on Inputs)
K = 20             # Newton iteration blocks in Engine_GrossUp

FONT = "Arial"
F_BASE = Font(name=FONT, size=10)
F_BOLD = Font(name=FONT, size=10, bold=True)
F_HEAD = Font(name=FONT, size=10, bold=True, color="FFFFFF")
F_TITLE = Font(name=FONT, size=14, bold=True)
F_NOTE = Font(name=FONT, size=9, italic=True, color="555555")
F_BLUE = Font(name=FONT, size=10, color="0000FF")
F_BLUEB = Font(name=FONT, size=10, color="0000FF", bold=True)
FILL_IN = PatternFill("solid", fgColor="FFFF00")         # V23: yellow = edit me
FILL_HEAD = PatternFill("solid", fgColor="0F766E")
FILL_DER = PatternFill("solid", fgColor="EEF1F2")
FILL_WARN = PatternFill("solid", fgColor="FDE2E1")
THIN = Side(style="thin", color="C3CDCF")
BOX = Border(top=THIN, bottom=THIN, left=THIN, right=THIN)

RUPEE = '"₹"#,##0;-"₹"#,##0;"–"'
PCT = '0.00%'
YEAR = '0'


def cell(ws, ref, value, font=F_BASE, fill=None, fmt=None, bold=False, align=None):
    c = ws[ref]
    c.value = value
    c.font = F_BOLD if bold else font
    if fill:
        c.fill = fill
    if fmt:
        c.number_format = fmt
    if align:
        c.alignment = Alignment(horizontal=align)
    return c


def header_row(ws, row, labels, start=1):
    for k, t in enumerate(labels):
        c = ws.cell(row=row, column=start + k, value=t)
        c.font = F_HEAD
        c.fill = FILL_HEAD
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
    ws.row_dimensions[row].height = 30


def name(wb, nm, ref):
    wb.defined_names[nm] = DefinedName(nm, attr_text=ref)


def build(model, out):
    s = model["state"]
    a = s["a"]
    inv = s["investments"]            # already in withdraw order (priority, then id)
    goals = s["goals"]
    N, G = len(inv), max(len(goals), 1)
    wb = Workbook()

    # ------------------------------------------------------------ Inputs
    ws = wb.active
    ws.title = "Inputs"
    cell(ws, "A1", "Goal Planner — inputs", F_TITLE)
    cell(ws, "A2", f"Generated by goal_planner {model['version']} from {model['source']} on "
         f"{model['generatedAt'][:16].replace('T', ' ')} UTC. Yellow cells are yours to edit; "
         "everything else is worked out from them. Regenerate from the planner rather than "
         "hand-editing formulas.", F_NOTE)
    rows = [
        ("As-of date (holding values are from this day)", "ASOF", date.fromisoformat(a["asOf"]), "yyyy-mm-dd", True),
        ("Current year", "CY", "=YEAR(ASOF)", YEAR, False),
        ("Age today", "CA", a["currentAge"], "0", True),
        ("Retirement age", "RA", a["retirementAge"], "0", True),
        ("Plan to age", "LE", a["lifeExpectancy"], "0", True),
        ("Return after retiring", "POSTRET", a["postRetReturn"], PCT, True),
        ("Switch every holding to that return at retirement", "USEPOST", bool(a.get("usePostRet")), None, True),
        ("Capital-gains exemption per year (withdrawal gains only)", "CGEX", a.get("cgExempt", 125000), RUPEE, True),
        (None, None, None, None, None),
        ("Retirement age used (kept between today's age and the plan's end)", "RAE", "=MAX(CA,MIN(RA,LE))", "0", False),
        ("Plan runs to age", "LEE", "=MAX(LE,RAE)", "0", False),
        ("Retirement year", "RY", "=CY+(RAE-CA)", YEAR, False),
        ("Plan end year", "EY", "=CY+(LEE-CA)", YEAR, False),
    ]
    r = 4
    for label, nm, val, fmt, is_in in rows:
        if label is None:
            r += 1
            continue
        cell(ws, f"A{r}", label)
        c = cell(ws, f"B{r}", val, fill=FILL_IN if is_in else FILL_DER, fmt=fmt)
        c.border = BOX
        name(wb, nm, f"Inputs!$B${r}")
        r += 1
    cell(ws, f"A{r+1}", "Years the workbook can show")
    cell(ws, f"B{r+1}", f"=CY+{MAXY - 1}", fill=FILL_DER, fmt=YEAR)
    cell(ws, f"C{r+1}", f'=IF(EY>B{r+1},"Plan is longer than the workbook — shorten it or regenerate","")',
         Font(name=FONT, size=10, bold=True, color="C00000"))
    usepost_row = 10
    dv = DataValidation(type="list", formula1='"TRUE,FALSE"', allow_blank=False)
    ws.add_data_validation(dv)
    dv.add(f"B{usepost_row}")
    ws.column_dimensions["A"].width = 62
    ws.column_dimensions["B"].width = 16

    # ------------------------------------------------------------ Portfolio
    wp = wb.create_sheet("Portfolio")
    cell(wp, "A1", "Portfolio — one row per holding, in withdraw order", F_TITLE)
    cell(wp, "A2", "Withdraw priority: 1 is sold first; holdings sharing a number give equal rupees. "
         "Tax rate 0% means exempt. Leave 'Invest till' blank to invest until retiring, 'Locked till' "
         "blank if it can be drawn any time. To add or remove a holding, do it in the planner and regenerate.",
         F_NOTE)
    ph = ["Holding", "Owner", "Category", "Include", "Value today (₹)", "Cost basis (₹)",
          "Added each year (₹)", "Step-up / yr", "Return / yr", "Invest till (year)", "Locked till (year)",
          "Tax timing", "Tax rate", "Withdraw priority", "id",
          "Order", "Stops investing after", "Taxed on withdrawal", "Taxed every year"]
    header_row(wp, 4, ph)
    P0 = 5
    for k, i in enumerate(inv):
        rr = P0 + k
        vals = [i["name"], i.get("owner", ""), i.get("cat", ""), bool(i.get("on", True)), i["val"],
                i.get("cost", i["val"]), i.get("add", 0), i.get("step", 0), i.get("ret", 0),
                i.get("until"), i.get("avail"),
                "Every year" if i.get("taxWhen") == "tax_at_year_end" else "On withdrawal",
                i.get("taxRate", 0), i.get("pri", 50), i["id"]]
        fmts = [None, None, None, None, RUPEE, RUPEE, RUPEE, PCT, PCT, YEAR, YEAR, None, PCT, "0", None]
        for c_, (v, f) in enumerate(zip(vals, fmts), start=1):
            x = wp.cell(row=rr, column=c_, value=v)
            x.font = F_BASE
            x.border = BOX
            if f:
                x.number_format = f
            if c_ <= 14:
                x.fill = FILL_IN
            else:
                x.fill = FILL_DER
        der = [
            f'=COUNTIFS($N${P0}:$N${P0+N-1},"<"&N{rr})+COUNTIFS($N${P0}:$N${P0+N-1},N{rr},$O${P0}:$O${P0+N-1},"<"&O{rr})+1',
            f'=IF(J{rr}="",RY-1,J{rr})',
            f'=IF(AND(L{rr}="On withdrawal",M{rr}>0),1,0)',
            f'=IF(L{rr}="Every year",1,0)',
        ]
        for c_, f in enumerate(der, start=16):
            x = wp.cell(row=rr, column=c_, value=f)
            x.font = F_BASE
            x.fill = FILL_DER
            x.border = BOX
    PL = P0 + N - 1
    dv2 = DataValidation(type="list", formula1='"On withdrawal,Every year"', allow_blank=False)
    dv3 = DataValidation(type="list", formula1='"TRUE,FALSE"', allow_blank=False)
    wp.add_data_validation(dv2)
    wp.add_data_validation(dv3)
    dv2.add(f"L{P0}:L{PL}")
    dv3.add(f"D{P0}:D{PL}")
    for c_, w in zip("ABCDEFGHIJKLMNOPQRS", [26, 10, 11, 8, 16, 16, 16, 10, 10, 11, 11, 14, 9, 10, 10, 7, 11, 11, 10]):
        wp.column_dimensions[c_].width = w
    wp.freeze_panes = "B5"

    def P(col, k):  # absolute reference into Portfolio for holding k
        return f"Portfolio!${col}${P0 + k}"

    # ------------------------------------------------------------ Goals
    wg = wb.create_sheet("Goals")
    cell(wg, "A1", "Goals — in today's money, each with its own inflation", F_TITLE)
    cell(wg, "A2", "Retirement spending runs from the retirement year to the end of the plan; its years follow "
         "Inputs. Essential goals are paid first; within that, earlier goals first.", F_NOTE)
    gh = ["Goal", "Kind", "Start year", "End year", "Amount a year, today's ₹", "Inflation", "Essential",
          "Include", "Retirement spending", "Starts", "Ends", "Sort key", "Paid in order",
          "Total due (₹)", "Total paid (₹)", "Short (₹)", "Status"]
    header_row(wg, 4, gh)
    G0 = 5
    GL = G0 + G - 1
    for k, g in enumerate(goals):
        rr = G0 + k
        vals = [g["name"], "Recurring" if g.get("kind") == "recurring" else "One-time", g["start"], g["end"],
                g["amt"], g.get("infl", 0), bool(g.get("ess")), bool(g.get("on", True)), bool(g.get("isRet"))]
        fmts = [None, None, YEAR, YEAR, RUPEE, PCT, None, None, None]
        for c_, (v, f) in enumerate(zip(vals, fmts), start=1):
            x = wg.cell(row=rr, column=c_, value=v)
            x.font = F_BASE
            x.border = BOX
            x.fill = FILL_IN if c_ <= 8 else FILL_DER
            if f:
                x.number_format = f
        der = [
            f"=IF(I{rr},RY,C{rr})",
            f'=IF(I{rr},EY,IF(B{rr}="One-time",J{rr},D{rr}))',
            f"=(1-G{rr})*10000+J{rr}",
            f'=COUNTIF($L${G0}:$L${GL},"<"&L{rr})+COUNTIF($L${G0-1}:L{rr-1},L{rr})+1',
        ]
        for c_, f in enumerate(der, start=10):
            x = wg.cell(row=rr, column=c_, value=f)
            x.font = F_BASE
            x.fill = FILL_DER
            x.border = BOX
    dvk = DataValidation(type="list", formula1='"One-time,Recurring"', allow_blank=False)
    dvb = DataValidation(type="list", formula1='"TRUE,FALSE"', allow_blank=False)
    wg.add_data_validation(dvk)
    wg.add_data_validation(dvb)
    dvk.add(f"B{G0}:B{GL}")
    dvb.add(f"G{G0}:H{GL}")
    for c_, w in zip("ABCDEFGHIJKLMNOPQ", [24, 11, 10, 10, 18, 10, 10, 9, 11, 9, 9, 9, 9, 16, 16, 14, 12]):
        wg.column_dimensions[c_].width = w

    # ------------------------------------------------------------ Engine sheets
    eg = wb.create_sheet("Engine_Growth")
    ew = wb.create_sheet("Engine_Withdraw")
    eu = wb.create_sheet("Engine_GrossUp")
    RG0 = 5                     # first year row in Engine_Growth
    RW0 = 10                    # first slot row in Engine_Withdraw / Engine_GrossUp
    S = G

    def grow_row(t):
        return RG0 + t

    def wrow(t, k):             # k = 0..S-1
        return RW0 + t * S + k

    # Engine_Growth columns: A t, B year, C age, D in plan, E retired, then field blocks of N
    FIELDS = ["OPEN", "BOPEN", "CONTRIB", "RATE", "GROW", "YTAX", "PRE", "PREB", "GF", "OPENF",
              "WD", "WDTAX", "CLOSE", "BCLOSE", "EMB"]
    FTITLE = {"OPEN": "Opening", "BOPEN": "Cost basis, opening", "CONTRIB": "Invested", "RATE": "Return",
              "GROW": "Growth (mid-year)", "YTAX": "Tax at year end", "PRE": "Before withdrawals",
              "PREB": "Cost basis before withdrawals", "GF": "Gain share", "OPENF": "Can be drawn",
              "WD": "Withdrawn", "WDTAX": "Tax on withdrawals", "CLOSE": "Closing",
              "BCLOSE": "Cost basis, closing", "EMB": "Tax still owed on gains"}
    gcol = {}
    c0 = 6
    for f in FIELDS:
        gcol[f] = [c0 + k for k in range(N)]
        c0 += N
    # per-year totals, always numeric (Year_by_year blanks the years outside the plan)
    TOT = ["OPENT", "CLOSET", "TAXT", "DUE", "SHORTT", "WDT", "DRY", "CLOSEM"]
    TTITLE = {"OPENT": "Opening, total", "CLOSET": "Closing, total", "TAXT": "Tax, total",
              "DUE": "Due this year", "SHORTT": "Unfunded", "WDT": "Withdrawn, total",
              "DRY": "Runs dry this year", "CLOSEM": "Closing (plan years only)"}
    tcol = {}
    for f in TOT:
        tcol[f] = c0
        c0 += 1

    # Engine_Withdraw columns
    wc = {}
    c0 = 1
    for f in ["T", "YEAR", "SLOT", "GI", "GNAME", "ISRET", "NEED", "ELEFT", "EEFF"]:
        wc[f] = c0
        c0 += 1
    wblocks = ["AV", "WDB", "GFB", "TG", "CF", "FN", "NB"]
    for f in wblocks:
        wc[f] = [c0 + k for k in range(N)]
        c0 += N
    for f in ["TOTNET", "DRAWALL", "PSTAR", "NEEDT", "GB", "HI0", "LAM"]:
        wc[f] = c0
        c0 += 1
    for f in ["PER", "GN", "CN", "TAX"]:
        wc[f] = [c0 + k for k in range(N)]
        c0 += N
    for f in ["EXUSED", "GROSS", "TAXT", "NET", "PAID", "SHORT"]:
        wc[f] = c0
        c0 += 1

    AVc = [L(x) for x in wc["AV"]]
    # attribute rows above the AV block, used as 1×N arrays by every SUMPRODUCT
    for k in range(N):
        col = AVc[k]
        for rr, v in [(3, f"={P('A', k)}"), (4, f"={P('N', k)}"), (5, f"={P('P', k)}"),
                      (6, f"={P('M', k)}"), (7, f"={P('R', k)}")]:
            x = ew[f"{col}{rr}"]
            x.value = v
            x.font = F_BASE
            x.fill = FILL_DER
    for rr, lab in [(3, "holding"), (4, "priority"), (5, "order"), (6, "tax rate"), (7, "taxed on withdrawal")]:
        cell(ew, f"{L(wc['AV'][0]-1)}{rr}", lab, F_NOTE, align="right")
    rng = lambda rr: f"Engine_Withdraw!${AVc[0]}${rr}:${AVc[-1]}${rr}"
    name(wb, "H_PRI", rng(4))
    name(wb, "H_RANK", rng(5))
    name(wb, "H_RATE", rng(6))
    name(wb, "H_TAXABLE", rng(7))
    PRI = lambda k: f"{AVc[k]}$4"
    RANK = lambda k: f"{AVc[k]}$5"
    RATE = lambda k: f"{AVc[k]}$6"
    TXB = lambda k: f"{AVc[k]}$7"

    def blk(f, rr, sheet=""):
        cs = wc[f]
        return f"{sheet}${L(cs[0])}{rr}:${L(cs[-1])}{rr}"

    # ---- Engine_Growth
    cell(eg, "A1", "Engine — growth, one row per year, one column per holding", F_TITLE)
    cell(eg, "A2", "growth = (opening + invested/2) × return. Tax charged every year is paid from that year's "
         "growth and joins the cost basis. Withdrawals come from Engine_Withdraw.", F_NOTE)
    for f in TOT:
        x = eg.cell(row=4, column=tcol[f], value=TTITLE[f])
        x.font = F_HEAD
        x.fill = FILL_HEAD
    for f in FIELDS:
        cs = gcol[f]
        x = eg.cell(row=3, column=cs[0], value=FTITLE[f])
        x.font = F_HEAD
        x.fill = FILL_HEAD
        for k in range(N):
            y = eg.cell(row=4, column=cs[k], value=f"={P('A', k)}")
            y.font = F_NOTE
    header_row(eg, 4, ["t", "Year", "Age", "In plan", "Retired"])
    for t in range(MAXY):
        rr = grow_row(t)
        eg.cell(row=rr, column=1, value=t)
        eg.cell(row=rr, column=2, value=f"=CY+A{rr}")
        eg.cell(row=rr, column=3, value=f"=CA+A{rr}")
        eg.cell(row=rr, column=4, value=f"=IF(B{rr}<=EY,1,0)")
        eg.cell(row=rr, column=5, value=f"=IF(B{rr}>=RY,1,0)")
        r1, rS = wrow(t, 0), wrow(t, S - 1)
        for k in range(N):
            g = {f: f"{L(gcol[f][k])}{rr}" for f in FIELDS}
            gp = {f: f"{L(gcol[f][k])}{rr-1}" for f in FIELDS}
            on = P("D", k)
            fm = {
                "OPEN": f"={on}*{P('E', k)}" if t == 0 else f"={gp['CLOSE']}",
                "BOPEN": f"={on}*{P('F', k)}" if t == 0 else f"={gp['BCLOSE']}",
                "CONTRIB": f"=IF(AND($B{rr}<={P('Q', k)},{P('G', k)}<>0),{on}*{P('G', k)}*(1+{P('H', k)})^($B{rr}-CY),0)",
                "RATE": f"=IF(AND(USEPOST,$B{rr}>=RY),POSTRET,{P('I', k)})",
                "GROW": f"=({g['OPEN']}+{g['CONTRIB']}/2)*{g['RATE']}",
                "YTAX": f"=IF(AND({P('S', k)}=1,{g['GROW']}>0),{g['GROW']}*{P('M', k)},0)",
                "PRE": f"={g['OPEN']}+{g['CONTRIB']}+{g['GROW']}-{g['YTAX']}",
                "PREB": f"={g['BOPEN']}+{g['CONTRIB']}+IF({P('S', k)}=1,{g['GROW']}-{g['YTAX']},0)",
                "GF": f"=IF({g['PRE']}>0,MAX(0,{g['PRE']}-{g['PREB']})/{g['PRE']},0)",
                "OPENF": f"=IF(OR({P('K', k)}=\"\",$B{rr}>={P('K', k)}),1,0)*{on}",
                "WD": f"=SUM(Engine_Withdraw!{L(wc['PER'][k])}{r1}:{L(wc['PER'][k])}{rS})",
                "WDTAX": f"=SUM(Engine_Withdraw!{L(wc['TAX'][k])}{r1}:{L(wc['TAX'][k])}{rS})",
                "CLOSE": f"={g['PRE']}-{g['WD']}",
                "BCLOSE": f"=MAX(0,{g['PREB']}-{g['WD']}*(1-{g['GF']}))",
                "EMB": f"=IF({P('L', k)}=\"On withdrawal\",MAX(0,{g['CLOSE']}-{g['BCLOSE']})*{P('M', k)},0)",
            }
            for f in FIELDS:
                x = eg[g[f]]
                x.value = fm[f]
                x.number_format = PCT if f in ("RATE", "GF") else ("0" if f == "OPENF" else RUPEE)
        rowsum = lambda f: f"SUM({L(gcol[f][0])}{rr}:{L(gcol[f][-1])}{rr})"
        wsum = lambda f: f"SUM(Engine_Withdraw!{L(wc[f])}{r1}:{L(wc[f])}{rS})"
        tf = {"OPENT": f"={rowsum('OPEN')}", "CLOSET": f"={rowsum('CLOSE')}",
              "TAXT": f"={rowsum('YTAX')}+{rowsum('WDTAX')}", "DUE": f"={wsum('NEED')}",
              "SHORTT": f"={wsum('SHORT')}", "WDT": f"={rowsum('WD')}",
              "DRY": f"=IF(AND(D{rr}=1,{L(tcol['CLOSET'])}{rr}<=1,{L(tcol['WDT'])}{rr}>0),1,0)",
              "CLOSEM": f"=IF(D{rr}=1,{L(tcol['CLOSET'])}{rr},-1E+300)"}
        for f in TOT:
            x = eg.cell(row=rr, column=tcol[f], value=tf[f])
            x.number_format = "0" if f == "DRY" else RUPEE
    eg.freeze_panes = eg.cell(row=RG0, column=6)

    # ---- Engine_Withdraw
    cell(ew, "A1", "Engine — withdrawals, one row per goal per year, in the order goals are paid", F_TITLE)
    cell(ew, "A2", "For each goal: what each holding still has, the tax a full draw of every withdraw band would "
         "cost (the yearly exemption is used up in withdraw order), the band where the need ends, and the "
         "final split. Engine_GrossUp finds the level inside that band.", F_NOTE)
    wlabels = {"T": "t", "YEAR": "Year", "SLOT": "Paid #", "GI": "Goal row", "GNAME": "Goal", "ISRET": "Retirement",
               "NEED": "Needed (₹)", "ELEFT": "Exemption left", "EEFF": "Exemption usable",
               "TOTNET": "Net if all drawn", "DRAWALL": "Draw everything", "PSTAR": "Band where need ends",
               "NEEDT": "Net still needed in that band", "GB": "Gains already drawn", "HI0": "Band's largest",
               "LAM": "Level in band", "EXUSED": "Exemption used", "GROSS": "Drawn, gross", "TAXT": "Tax",
               "NET": "Net", "PAID": "Paid", "SHORT": "Short"}
    btitle = {"AV": "Available", "WDB": "Drawn earlier this year", "GFB": "Gain share", "TG": "Gain if all drawn",
              "CF": "Cumulative gain", "FN": "Net if all drawn", "NB": "Net from earlier bands",
              "PER": "Drawn", "GN": "Gain drawn", "CN": "Cumulative gain drawn", "TAX": "Tax"}
    for f, lab in wlabels.items():
        x = ew.cell(row=9, column=wc[f], value=lab)
        x.font = F_HEAD
        x.fill = FILL_HEAD
        x.alignment = Alignment(wrap_text=True)
    for f, lab in btitle.items():
        x = ew.cell(row=8, column=wc[f][0], value=lab)
        x.font = F_BOLD
        for k in range(N):
            y = ew.cell(row=9, column=wc[f][k], value=f"={P('A', k)}")
            y.font = F_HEAD
            y.fill = FILL_HEAD
    ew.row_dimensions[9].height = 30

    WC = lambda f, rr: f"{L(wc[f])}{rr}"
    WB = lambda f, k, rr: f"{L(wc[f][k])}{rr}"
    for t in range(MAXY):
        gr = grow_row(t)
        for s_ in range(S):
            rr = wrow(t, s_)
            gidx = WC("GI", rr)
            ew.cell(row=rr, column=wc["T"], value=t)
            ew.cell(row=rr, column=wc["YEAR"], value=f"=Engine_Growth!B{gr}")
            ew.cell(row=rr, column=wc["SLOT"], value=s_ + 1)
            ew.cell(row=rr, column=wc["GI"], value=f"=IFERROR(MATCH({WC('SLOT', rr)},Goals!$M${G0}:$M${GL},0),0)")
            ew.cell(row=rr, column=wc["GNAME"], value=f'=IF({gidx}>0,INDEX(Goals!$A${G0}:$A${GL},{gidx}),"")')
            ew.cell(row=rr, column=wc["ISRET"], value=f"=IF({gidx}>0,IF(INDEX(Goals!$I${G0}:$I${GL},{gidx}),1,0),0)")
            yr = WC("YEAR", rr)
            ix = lambda col: f"INDEX(Goals!${col}${G0}:${col}${GL},{gidx})"
            ew.cell(row=rr, column=wc["NEED"], value=(
                f"=IF({gidx}>0,IF(AND(Engine_Growth!$D{gr}=1,{ix('H')},{yr}>={ix('J')},{yr}<={ix('K')}),"
                f"{ix('E')}*(1+{ix('F')})^({yr}-CY),0),0)"))
            ew.cell(row=rr, column=wc["ELEFT"], value=(
                "=CGEX" if s_ == 0 else f"={WC('EEFF', rr-1)}-{WC('EXUSED', rr-1)}"))
            ew.cell(row=rr, column=wc["EEFF"], value=f"=MAX(0,{WC('ELEFT', rr)})")
            E = WC("EEFF", rr)
            for k in range(N):
                pre = f"Engine_Growth!{L(gcol['PRE'][k])}{gr}"
                gf = f"Engine_Growth!{L(gcol['GF'][k])}{gr}"
                opn = f"Engine_Growth!{L(gcol['OPENF'][k])}{gr}"
                wdb = "0" if s_ == 0 else f"{WB('WDB', k, rr-1)}+{WB('PER', k, rr-1)}"
                ew.cell(row=rr, column=wc["WDB"][k], value=f"={wdb}")
                ew.cell(row=rr, column=wc["AV"][k], value=f"=MAX({pre}-{WB('WDB', k, rr)},0)*{opn}")
                ew.cell(row=rr, column=wc["GFB"][k], value=f"={gf}")
                ew.cell(row=rr, column=wc["TG"][k], value=f"={TXB(k)}*{WB('GFB', k, rr)}*{WB('AV', k, rr)}")
                ew.cell(row=rr, column=wc["CF"][k], value=f"=SUMPRODUCT((H_RANK<={RANK(k)})*{blk('TG', rr)})")
                cf, tg = WB("CF", k, rr), WB("TG", k, rr)
                ew.cell(row=rr, column=wc["FN"][k],
                        value=f"={WB('AV', k, rr)}-{RATE(k)}*(MAX(0,{cf}-{E})-MAX(0,{cf}-{tg}-{E}))")
                ew.cell(row=rr, column=wc["NB"][k], value=f"=SUMPRODUCT((H_PRI<{PRI(k)})*{blk('FN', rr)})")
            need = WC("NEED", rr)
            ps = WC("PSTAR", rr)
            ew.cell(row=rr, column=wc["TOTNET"], value=f"=SUM({blk('FN', rr)})")
            ew.cell(row=rr, column=wc["DRAWALL"], value=f"=IF({WC('TOTNET', rr)}<={need}+0.000001,1,0)")
            ew.cell(row=rr, column=wc["PSTAR"],
                    value=f"=SUMPRODUCT(MAX(({blk('NB', rr)}<={need})*({blk('AV', rr)}>0)*H_PRI))")
            ew.cell(row=rr, column=wc["NEEDT"], value=f"=MAX(0,{need}-SUMPRODUCT((H_PRI<{ps})*{blk('FN', rr)}))")
            ew.cell(row=rr, column=wc["GB"], value=f"=SUMPRODUCT((H_PRI<{ps})*{blk('TG', rr)})")
            ew.cell(row=rr, column=wc["HI0"], value=f"=SUMPRODUCT(MAX((H_PRI={ps})*{blk('AV', rr)}))")
            ew.cell(row=rr, column=wc["LAM"], value=f"=Engine_GrossUp!{L(3 + K * (3 + 2 * N + 2))}{rr}")
            lam = WC("LAM", rr)
            for k in range(N):
                av = WB("AV", k, rr)
                ew.cell(row=rr, column=wc["PER"][k], value=(
                    f"=IF({WC('DRAWALL', rr)}=1,{av},IF({PRI(k)}<{ps},{av},IF({PRI(k)}={ps},MIN({av},{lam}),0)))"))
                ew.cell(row=rr, column=wc["GN"][k], value=f"={TXB(k)}*{WB('GFB', k, rr)}*{WB('PER', k, rr)}")
                ew.cell(row=rr, column=wc["CN"][k], value=f"=SUMPRODUCT((H_RANK<={RANK(k)})*{blk('GN', rr)})")
                cn, gn = WB("CN", k, rr), WB("GN", k, rr)
                ew.cell(row=rr, column=wc["TAX"][k],
                        value=f"={RATE(k)}*(MAX(0,{cn}-{E})-MAX(0,{cn}-{gn}-{E}))")
            ew.cell(row=rr, column=wc["EXUSED"], value=f"=MIN({E},SUM({blk('GN', rr)}))")
            ew.cell(row=rr, column=wc["GROSS"], value=f"=SUM({blk('PER', rr)})")
            ew.cell(row=rr, column=wc["TAXT"], value=f"=SUM({blk('TAX', rr)})")
            ew.cell(row=rr, column=wc["NET"], value=f"={WC('GROSS', rr)}-{WC('TAXT', rr)}")
            ew.cell(row=rr, column=wc["PAID"], value=f"=MIN({WC('NET', rr)},{need})")
            ew.cell(row=rr, column=wc["SHORT"], value=f"=MAX({need}-{WC('NET', rr)},0)")
    ew.freeze_panes = ew.cell(row=RW0, column=wc["NEED"])

    # ---- Engine_GrossUp
    cell(eu, "A1", "Engine — gross-up inside the band where the need ends", F_TITLE)
    cell(eu, "A2", "Holdings in the band give equal rupees up to a level λ (a holding that runs dry gives what "
         "it has). Net after tax is piecewise linear in λ, so each block takes an exact Newton step on the "
         "current slope, kept inside a shrinking bracket. The last column is the level used.", F_NOTE)
    BW = 3 + 2 * N + 2
    for rr in range(RW0, RW0 + MAXY * S):
        eu.cell(row=rr, column=1, value=f"=Engine_Withdraw!{L(wc['YEAR'])}{rr}")
