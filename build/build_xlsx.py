    header_row(wa, 10, ["Year", "Needed at the start of the year (₹)", "Needed by year end (₹)",
                        "Closing, as projected (₹)", "Surplus (+) or short (−) (₹)"])
    req, reqE = model["required"], model["requiredEnd"]
    for t, y in enumerate(model["years"]):
        rr = 11 + t
        e = reqE[t] if reqE else None
        for c_, v in enumerate([y["year"], req[t] if req else None, e, y["closing"],
                                None if e is None else y["closing"] - e], start=1):
            x = wa.cell(row=rr, column=c_, value=v)
            x.font = F_BLUE
            x.number_format = YEAR if c_ == 1 else RUPEE
    wa.column_dimensions["A"].width = 60
    for c_ in "BCDE":
        wa.column_dimensions[c_].width = 22
    ac = LineChart()
    ac.title = "Projected corpus against what the goals need (as generated)"
    ac.height, ac.width = 8, 18
    last = 10 + len(model["years"])
    ac.add_data(Reference(wa, min_col=3, max_col=4, min_row=10, max_row=last), titles_from_data=True)
    ac.set_categories(Reference(wa, min_col=1, min_row=11, max_row=last))
    wa.add_chart(ac, "G3")

    order = ["Dashboard", "Inputs", "Portfolio", "Goals", "Year_by_year", "Analysis",
             "Engine_Growth", "Engine_Withdraw", "Engine_GrossUp"]
    wb._sheets = [wb[n] for n in order]
    wb.active = 0
    for sheet in wb.worksheets:
        sheet.sheet_view.showGridLines = sheet.title not in ("Dashboard", "Analysis")
    wb.calculation.fullCalcOnLoad = True
    wb.save(out)
    return {"holdings": N, "goals": len(goals), "years": len(model["years"])}


